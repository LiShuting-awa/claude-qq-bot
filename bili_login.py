"""一次性 B 站扫码登录：生成二维码，等待扫码，成功后写入 .env。"""

from __future__ import annotations

import asyncio
import os
import time
from pathlib import Path

from bilibili_api import login_v2

ROOT = Path(__file__).resolve().parent
QR_PATH = ROOT / "logs" / "bili-login-qr.png"
STATUS_PATH = ROOT / "logs" / "bili-login-status.txt"
ENV_PATH = ROOT / ".env"
COOKIE_PATH = ROOT / "data" / "bili_cookies.txt"


def set_status(value: str) -> None:
    STATUS_PATH.write_text(value, encoding="utf-8")


def update_env(values: dict[str, str]) -> None:
    text = ENV_PATH.read_text(encoding="utf-8") if ENV_PATH.exists() else ""
    lines = text.splitlines()
    output: list[str] = []
    seen: set[str] = set()
    for line in lines:
        key = line.split("=", 1)[0].strip() if "=" in line else ""
        if key in values:
            output.append(f"{key}={values[key]}")
            seen.add(key)
        else:
            output.append(line)
    for key, value in values.items():
        if key not in seen:
            output.append(f"{key}={value}")
    ENV_PATH.write_text("\n".join(output).rstrip() + "\n", encoding="utf-8")


def write_cookie_file(sessdata: str, bili_jct: str, buvid3: str, buvid4: str, dedeuserid: str) -> None:
    COOKIE_PATH.parent.mkdir(parents=True, exist_ok=True)
    rows = [
        ("SESSDATA", sessdata),
        ("bili_jct", bili_jct),
        ("buvid3", buvid3),
        ("buvid4", buvid4),
        ("DedeUserID", dedeuserid),
    ]
    lines = ["# Netscape HTTP Cookie File", "# generated by qqbot bilibili login"]
    for name, value in rows:
        if value:
            lines.append(f".bilibili.com\tTRUE\t/\tTRUE\t0\t{name}\t{value}")
    COOKIE_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def main() -> None:
    set_status("generating")
    platform = (
        login_v2.QrCodeLoginChannel.TV
        if os.environ.get("BILI_QR_PLATFORM", "").upper() == "TV"
        else login_v2.QrCodeLoginChannel.WEB
    )
    qr = login_v2.QrCodeLogin(platform=platform)
    await qr.generate_qrcode()
    qr.get_qrcode_picture().to_file(str(QR_PATH))
    set_status("waiting")
    print("QR_READY", flush=True)

    deadline = time.time() + 240
    last_state = "waiting"
    while time.time() < deadline:
        state = await qr.check_state()
        if state == login_v2.QrCodeLoginEvents.CONF and last_state != "scanned":
            last_state = "scanned"
            set_status("scanned")
        elif state == login_v2.QrCodeLoginEvents.DONE:
            credential = qr.get_credential()
            if credential is None:
                set_status("error:no_credential")
                return
            values = {
                "BILI_SESSDATA": credential.sessdata or "",
                "BILIBILI_NATIVE_AUTO": "true",
                "MEDIA_COOKIES_FILE": str(COOKIE_PATH).replace("\\", "/"),
            }
            update_env(values)
            write_cookie_file(
                credential.sessdata or "",
                credential.bili_jct or "",
                credential.buvid3 or "",
                credential.buvid4 or "",
                credential.dedeuserid or "",
            )
            set_status("done")
            print("LOGIN_DONE", flush=True)
            return
        elif state == login_v2.QrCodeLoginEvents.TIMEOUT:
            set_status("expired")
            print("QR_EXPIRED", flush=True)
            return
        await asyncio.sleep(2)

    set_status("expired")
    print("QR_EXPIRED", flush=True)


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except Exception as exc:
        set_status(f"error:{type(exc).__name__}:{str(exc)[:200]}")
        raise
